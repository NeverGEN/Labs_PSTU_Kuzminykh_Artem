#include <iostream>
#include <cstdlib>
#include <ctime>

using namespace std;

int main() {
    setlocale(LC_ALL, ".UTF8");
    srand(static_cast<unsigned int>(time(nullptr)));

    const int N = 100; // Максимальная длина статического массива
    int a[N];          // Объявление статического массива
    int n;             // Реальная длина массива

    // Ввод реальной длины пользователем
    cout << "Введите длину массива n (5<n<" << N << "): ";
    cin >> n;

    if (n <= 5 || n > N) {
        cout << "Ошибка" << N << endl;
        return 1;
    }

    // Формирование массива с помощью датчика случайных чисел (от -10 до 40)
    for (int i = 0; i < n; ++i) {
        a[i] = rand() % 51 - 10;
    }

    // Выводим полученный массив
    cout << "Исходный массив: " << endl;
    for (int i = 0; i < n; ++i) {
        cout << a[i] << " ";
    }
    cout << endl;

    // Удалить 5 последних элементов (просто уменьшаем реальную длину)
    n -= 5;

    cout << "Массив после удаления 5 последних элементов:" << endl;
    for (int i = 0; i < n; ++i) {
        cout << a[i] << " ";
    }
    cout << endl;

    // Добавить в начало массива 3 элемента со значением M[I+1] + 2
    int val0 = a[1] + 2;
    int val1 = a[2] + 2;
    int val2 = a[3] + 2;

    // Сдвигаем все текущие элементы вправо на 3 позиции
    for (int i = n - 1; i >= 0; --i) {
        a[i + 3] = a[i];
    }

    // Увеличиваем реальную длину массива на 3
    n += 3;

    // Записываем новые элементы в начало
    a[0] = val0;
    a[1] = val1;
    a[2] = val2;

    // Выводим полученный массив
    cout << "Итоговый массив (длина: " << n << "):" << endl;
    for (int i = 0; i < n; ++i) {
        cout << a[i] << " ";
    }
    cout << endl;

    return 0;
}